# 动态追加的术语文件路径
_DYNAMIC_FILE = Path(__file__).parent / "company_glossary_dynamic.json"

# 线程锁
_lock = threading.Lock()

# 内存缓存（进程启动时加载一次）
_dynamic_cache: dict[str, str] | None = None


def _load_dynamic_glossary() -> dict[str, str]:
    """加载动态追加的术语（带内存缓存）"""
    global _dynamic_cache
    if _dynamic_cache is not None:
        return _dynamic_cache

    if _DYNAMIC_FILE.exists():
        try:
            with open(_DYNAMIC_FILE, "r", encoding="utf-8") as f:
                _dynamic_cache = json.load(f)
                return _dynamic_cache
        except (json.JSONDecodeError, IOError):
            _dynamic_cache = {}
    else:
        _dynamic_cache = {}
    return _dynamic_cache


def _invalidate_cache() -> None:
    """使缓存失效（新增术语后调用）"""
    global _dynamic_cache
    _dynamic_cache = None


def _save_dynamic_glossary(data: dict[str, str]) -> None:
    """保存动态追加的术语"""
    with open(_DYNAMIC_FILE, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    # 保存后使缓存失效
    _invalidate_cache()


def get_term_explanation(term: str) -> str | None:
    """
    根据术语名称获取解释（先查预定义，再查动态库）

    Args:
        term: 术语名称

    Returns:
        术语解释，如果未找到则返回 None
    """
    result = PREDEFINED_GLOSSARY.get(term)
    if result:
        return result

    dynamic = _load_dynamic_glossary()
    return dynamic.get(term)


def add_term(term: str, explanation: str) -> bool:
    """
    将新术语写入动态知识库（异步非阻塞）

    Args:
        term: 术语
        explanation: 解释

    Returns:
        是否写入成功
    """
    if not term or not explanation:
        return False

    # 先检查是否已存在
    if term in PREDEFINED_GLOSSARY:
        return True

    dynamic = _load_dynamic_glossary()
    if term in dynamic:
        return True

    dynamic[term] = explanation
    _save_dynamic_glossary(dynamic)
    return True


def async_add_term(term: str, explanation: str) -> None:
    """异步写入术语，不阻塞主线程"""
    thread = threading.Thread(target=add_term, args=(term, explanation), daemon=True)
    thread.start()


def match_terms_in_text(text: str) -> list[dict[str, str]]:
    """
    在文本中匹配公司专有名词

    Args:
        text: 待匹配的文本

    Returns:
        匹配到的术语列表，包含术语名称和解释
    """
    if not text:
        return []

    dynamic = _load_dynamic_glossary()
    all_glossary = {**PREDEFINED_GLOSSARY, **dynamic}

    matched = []
    for term, explanation in sorted(all_glossary.items(), key=lambda x: -len(x[0])):
        if term in text and term not in [m["term"] for m in matched]:
            matched.append({"term": term, "explanation": explanation})

    return matched
